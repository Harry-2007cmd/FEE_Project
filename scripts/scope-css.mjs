// Regenerates src/styles/*.css from the untouched originals in public/legacy.
// Every page stylesheet is scoped to the <body data-page="..."> values whose
// original HTML loaded it, so selectors that collide between pages
// (.link-button, .upcoming, ...) cannot leak across routes.
// styles.css is global and copied unchanged.  Run: node scripts/scope-css.mjs
import fs from "node:fs";
import path from "node:path";

const SRC = "public/legacy";
const OUT = "src/styles";
const MAP = {
  "home.css": ["home"],
  "trainers.css": ["trainers"],
  "courses.css": ["courses", "course", "coach", "lesson", "planner"],
  "course-detail.css": ["course", "coach", "lesson"],
  "coach.css": ["coach"],
  "lesson.css": ["lesson"],
  "planner.css": ["planner"],
  "pricing.css": ["pricing"],
  "profile.css": ["profile"],
  "tools.css": ["tools"],
  "auth.css": ["login", "signup"],
};

function splitTop(s, sep) {
  const parts = []; let depth = 0, cur = "", q = "";
  for (const ch of s) {
    if (q) { cur += ch; if (ch === q) q = ""; continue; }
    if (ch === '"' || ch === "'") { q = ch; cur += ch; continue; }
    if ("([".includes(ch)) depth++;
    if (")]".includes(ch)) depth--;
    if (ch === sep && depth === 0) { parts.push(cur); cur = ""; } else cur += ch;
  }
  parts.push(cur);
  return parts;
}

function scopeSelector(sel, pages) {
  const prefix = pages.length === 1
    ? `body[data-page="${pages[0]}"]`
    : `body:is(${pages.map((p) => `[data-page="${p}"]`).join(", ")})`;
  return splitTop(sel, ",").map((s) => `${prefix} ${s.trim()}`).join(",\n");
}

// Minimal block parser: returns nodes {prelude, body|null(decl-only)}.
function parse(css) {
  const nodes = []; let i = 0;
  while (i < css.length) {
    let j = i, depth = 0, q = "";
    while (j < css.length) {
      const ch = css[j];
      if (q) { if (ch === q) q = ""; }
      else if (ch === '"' || ch === "'") q = ch;
      else if (ch === "{") break;
      else if (ch === ";" ) break;
      j++;
    }
    const prelude = css.slice(i, j).trim();
    if (css[j] === ";") { if (prelude) nodes.push({ prelude, body: null }); i = j + 1; continue; }
    if (j >= css.length) break;
    let k = j + 1; depth = 1; q = "";
    while (k < css.length && depth) {
      const ch = css[k];
      if (q) { if (ch === q) q = ""; }
      else if (ch === '"' || ch === "'") q = ch;
      else if (ch === "{") depth++;
      else if (ch === "}") depth--;
      k++;
    }
    nodes.push({ prelude, body: css.slice(j + 1, k - 1) });
    i = k;
  }
  return nodes;
}

function scope(css, pages) {
  return parse(css).map((n) => {
    if (n.body === null) return `${n.prelude};`;
    if (/^@(media|supports|layer)/i.test(n.prelude))
      return `${n.prelude} {\n${scope(n.body, pages).replace(/^/gm, "  ")}\n}`;
    if (/^@/.test(n.prelude)) return `${n.prelude} {${n.body}}`; // keyframes etc.
    return `${scopeSelector(n.prelude, pages)} {${n.body}}`;
  }).join("\n\n");
}

fs.mkdirSync(OUT, { recursive: true });
fs.copyFileSync(path.join(SRC, "styles.css"), path.join(OUT, "styles.css"));
for (const [file, pages] of Object.entries(MAP)) {
  const raw = fs.readFileSync(path.join(SRC, file), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  const header = `/* GENERATED by scripts/scope-css.mjs from public/legacy/${file} — do not edit by hand.\n   Scoped to body[data-page] = ${pages.join(", ")} */\n\n`;
  fs.writeFileSync(path.join(OUT, file), header + scope(raw, pages) + "\n");
  console.log(file, "->", pages.join(","));
}
